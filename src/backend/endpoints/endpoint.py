# Absolute paths: the server works the same whatever folder uvicorn is started from.
BACKEND_ROOT = Path(__file__).resolve().parents[1]      # src/backend
WORKSPACE_ROOT = BACKEND_ROOT / "workspace"
WORKSPACE_ROOT.mkdir(exist_ok=True)
DATA_ROOT = BACKEND_ROOT / "data"
# Everything that holds user code or run output: clones/snippets (+ _stage4_orig/_tests_orig backups, venvs),
# audit reports/diffs/parity.json, downloaded run output (data/runs), and the LLM reply caches (prompts embed
# source). Kept: grounding cache (public docs) and telemetry.jsonl (token counts only, no code).
# REFORGE_KEEP_CACHE=1 keeps the plan/patch caches (deterministic demo reruns at $0).
RUNS_DIR = DATA_ROOT / "runs"      # put client downloads (out.json, report.pdf) here, not in the repo
PURGE_DIRS = [WORKSPACE_ROOT, DATA_ROOT / "audit", RUNS_DIR]
if os.environ.get("REFORGE_KEEP_CACHE") != "1":
    PURGE_DIRS += [DATA_ROOT / "cache" / "plans", DATA_ROOT / "cache" / "patches"]
KEEP_DIRS = (".harness_venv", ".sandbox_venv")   # survive a refresh -> no venv rebuild on re-runs
GIT_TIMEOUT = 90
SNIPPET_FILE, SNIPPET_TEST = "snippet.py", "test_snippet.py"

# Generated test: the pasted snippet becomes the test signal. Under v1 (baseline) it runs the snippet and
# records its stdout; under v2 / after patching it must run without error AND print exactly the same.
SNIPPET_TEST_SRC = '''"""Generated by Reforge. Runs snippet.py as a test: it must execute and print what it printed under v1."""
import pathlib
import runpy

HERE = pathlib.Path(__file__).resolve().parent
GOLDEN = HERE / ".snippet_output.txt"


def test_snippet_runs_and_output_unchanged(capsys):
    runpy.run_path(str(HERE / "snippet.py"), run_name="__main__")
    out = capsys.readouterr().out
    if GOLDEN.is_file():
        assert out == GOLDEN.read_text(encoding="utf-8"), "snippet output differs from the v1 baseline"
    else:  # first (baseline) run records the reference output
        GOLDEN.write_text(out, encoding="utf-8")
'''


def _force_writable(func, path, _exc):
    """rmtree error hook: git marks objects read-only, which Windows refuses to delete."""
    for p in (path, os.path.dirname(path)):
        try:
            os.chmod(p, stat.S_IWRITE | stat.S_IREAD | stat.S_IEXEC)
        except OSError:
            pass
    func(path)


def remove_tree(path: Path) -> None:
    if path.exists():
        shutil.rmtree(path, onexc=_force_writable)


_purged = False


def purge_user_data(reason: str) -> None:
    """Delete every directory that may hold user code. Runs on startup (covers a crash / killed
    process last time), on graceful shutdown, and at interpreter exit."""
    global _purged
    if _purged and reason == "exit":
        return
    for d in PURGE_DIRS:
        try:
            remove_tree(d)
        except OSError as e:   # a still-running test process can hold a file open on Windows
            print(f"[reforge] purge ({reason}): could not fully delete {d}: {e}")
    WORKSPACE_ROOT.mkdir(exist_ok=True)
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    _purged = reason == "shutdown"
    print(f"[reforge] purged user data ({reason})")


@asynccontextmanager
async def lifespan(_app: FastAPI):
    purge_user_data("startup")
    atexit.register(purge_user_data, "exit")    # server processes only, not every importer of this module
    yield
    purge_user_data("shutdown")


app = FastAPI(lifespan=lifespan)


def reset_dir(path: Path, keep: tuple[str, ...] = KEEP_DIRS) -> None:
    """Empty `path` except the reusable venvs (stale snippet, golden output, reports, generated requirements)."""
    path.mkdir(parents=True, exist_ok=True)
    for child in path.iterdir():
        if child.name in keep:
            continue
        if child.is_dir() and not child.is_symlink():
            remove_tree(child)
        else:
            try:
                child.unlink()
            except PermissionError:
                os.chmod(child, stat.S_IWRITE)
                child.unlink()


def write_snippet_workspace(ws_path: Path, code: str) -> None:
    reset_dir(ws_path)
    (ws_path / SNIPPET_FILE).write_text(code, encoding="utf-8")
    (ws_path / SNIPPET_TEST).write_text(SNIPPET_TEST_SRC, encoding="utf-8")


def check_python(code: str, raw: str) -> None:
    """Fail fast (no tokens/credits spent) when the snippet is not valid Python."""
    try:
        ast.parse(code)
    except SyntaxError as e:
        hint = ""
        if raw.count("\n") == 0 and len(raw) > 120:
            hint = (" The snippet arrived as a single line: multi-line code pasted into a one-line form field "
                    "(e.g. Swagger UI) loses its newlines. Upload it via `code_file`, or send it with "
                    "curl -F \"code_snippet=<file.py\".")
        raise HTTPException(status_code=422,
                            detail=f"Snippet is not valid Python: line {e.lineno}: {e.msg}.{hint}")


def _git(*args: str, cwd: Path | None = None) -> None:
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True, timeout=GIT_TIMEOUT)


def sync_repo(url: str, ws_path: Path) -> str:
    """Existing clone -> hard refresh to the remote HEAD (keeps venvs); otherwise fresh clone."""
    if (ws_path / ".git").is_dir():
        try:
            _git("remote", "set-url", "origin", url, cwd=ws_path)
            _git("fetch", "--depth", "1", "origin", "HEAD", cwd=ws_path)
            _git("reset", "--hard", "FETCH_HEAD", cwd=ws_path)
            _git("clean", "-ffdx", *[a for d in KEEP_DIRS for a in ("-e", d)], cwd=ws_path)
            return "refreshed"
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired):
            pass   # broken clone -> start over
    remove_tree(ws_path)
    _git("clone", "--depth", "1", url, str(ws_path))
    return "cloned"


@app.post("/api/run-pipeline")
def run_pipeline(
    content: Optional[str] = Form(None),
    repo_url: Optional[str] = Form(None),
    code_snippet: Optional[str] = Form(None),
    # Plain `UploadFile` + format=binary: Swagger UI only renders a file picker for that schema
    # (Optional[UploadFile] becomes anyOf[file, null], which /docs shows as nothing).
    code_file: UploadFile = File(None, json_schema_extra={"format": "binary"},
                                 description="A .py file with Pydantic v1 code (keeps newlines, unlike the text box)")):

    t0 = time.perf_counter()
    timings: dict[str, float] = {}
    raw_input = (content or repo_url or code_snippet or "").strip()
    if code_file is not None and code_file.filename:      # upload keeps newlines intact
        raw_input = code_file.file.read().decode("utf-8-sig", errors="replace").strip()
    if not raw_input:
        raise HTTPException(status_code=400, detail="Missing input content.")

    # Stray quotes only matter for URLs; stripping them from code would eat docstring quotes
    valid_url = normalize_github_url(raw_input.strip("\"'"))
    print(f"[DEBUG] Normalized URL result: {valid_url}")

    if valid_url:
        input_type = "github"
        repo_name = valid_url.rstrip("/").split("/")[-1].replace(".git", "")
        ws_path = WORKSPACE_ROOT / repo_name
        try:
            workspace_action = sync_repo(valid_url, ws_path)
        except subprocess.CalledProcessError as e:
            raise HTTPException(status_code=502, detail=f"git {e.cmd[1]} failed: {(e.stderr or '').strip()[-400:]}")
        except subprocess.TimeoutExpired:
            raise HTTPException(status_code=504, detail=f"git timed out after {GIT_TIMEOUT}s")
        except OSError as e:
            raise HTTPException(status_code=500, detail=f"could not reset workspace {ws_path.name}: {e}")
    else:
        input_type = "text"
        ws_path = WORKSPACE_ROOT / "text"
        code = normalize_pasted_code(raw_input)
        check_python(code, raw_input)
        try:
            write_snippet_workspace(ws_path, code)
        except OSError as e:
            raise HTTPException(status_code=500, detail=f"could not reset workspace text: {e}")
        workspace_action = "snippet"
    print(f"[DEBUG] Workspace {ws_path.name}: {workspace_action}")
    lap = t0   # first lap = input normalisation + clone

    def mark(name: str) -> None:
        nonlocal lap
        now = time.perf_counter()
        timings[name] = round(now - lap, 2)
        lap = now

    mark("input + clone")
    scan_result = scan_environment(ws_path, input_type=input_type)
    mark("stage1_scan")
    baseline_metrics = run_harness(ws_path)
    mark("stage1_baseline_tests")
    stage2 = run_stage2(ws_path, baseline=baseline_metrics, target_version=scan_result["latest_version"])
    mark("stage2_break_run")
    stage3 = run_stage3(ws_path, stage2)
    mark("stage3_ground_plan")
    stage4 = run_stage4(ws_path, stage3, stage2=stage2, baseline=baseline_metrics)
    mark("stage4_patch_verify")
    result = {"input_type": input_type, "workspace": workspace_action, "scan": scan_result,
              "baseline": baseline_metrics, "stage2": stage2, "stage3": stage3, "stage4": stage4}
    result["stage5"] = run_stage5(ws_path, result)
    mark("stage5_parity_report")
    timings["total"] = round(time.perf_counter() - t0, 2)
    print(f"[TIMING] {timings}")
    return {"timings_s": timings, **result}

@app.get("/api/report/{name}")
def download_report(name: str):
    pdf = DATA_ROOT / "audit" / Path(name).name / "report.pdf"
    if not pdf.is_file():
        raise HTTPException(404, "no report yet")
    return FileResponse(pdf, media_type="application/pdf", filename=f"reforge_{name}.pdf")
